class TestHappyPath:
    def test_valid_edge_runs_all_hooks_in_order(self, tmp_path: Path) -> None:
        repo, vault, plan, env = _setup(tmp_path)

        result = _run_transition(
            repo, env, "awaiting-plan-review", str(plan)
        )
        assert result.returncode == 0, result.stderr

        # Frontmatter updated: status + planned + commit.
        from booping.context._yaml import parse_frontmatter_only

        fm = parse_frontmatter_only(plan)
        assert fm["status"] == "awaiting-plan-review"
        assert fm["planned"] not in (None, "null", "")
        assert fm["commit"] not in (None, "null", "")

        # sprints.md regenerated (booping snapshot header replaces the stub).
        assert "Snapshot generated by booping render-sprints" in (
            vault / "sprints.md"
        ).read_text()

        # Exactly one new vault commit, naming the target status + plan stem.
        log = _git(vault, ["log", "--oneline"]).stdout.strip().splitlines()
        assert len(log) == 2  # initial + the transition commit
        assert "awaiting-plan-review: 20260101-my-feature" in log[0]


