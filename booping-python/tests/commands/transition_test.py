# 5. Idempotent re-run
# ---------------------------------------------------------------------------

class TestIdempotentRerun:
    def test_status_already_target_runs_only_post_hooks(
        self, tmp_path: Path
    ) -> None:
        repo, vault, plan, env = _setup(tmp_path)

        # First move in-spec → awaiting-plan-review.
        first = _run_transition(repo, env, "awaiting-plan-review", str(plan))
        assert first.returncode == 0, first.stderr

        # Give vault-commit a real change to commit on the re-run by editing the
        # plan body (render-sprints regenerates a byte-identical snapshot, so the
        # plan edit is what proves vault-commit re-ran end-to-end).
        plan.write_text(plan.read_text() + "\nExtra note.\n")

        # Re-run targeting the same status: the missing in-spec edge must NOT
        # error; the dispatcher must take the idempotent path.
        second = _run_transition(repo, env, "awaiting-plan-review", str(plan))
        assert second.returncode == 0, second.stderr

        # Report: idempotent header + post-hook lines only (no frontmatter line).
        lines = second.stdout.strip().splitlines()
        assert lines[0] == "awaiting-plan-review → awaiting-plan-review (idempotent)"
        assert not any(line.startswith("frontmatter:") for line in lines)

        # render-sprints post-hook ran.
        assert f"render-sprints: 1 plans → {vault / 'sprints.md'}" in lines
        assert "Snapshot generated by booping render-sprints" in (
            vault / "sprints.md"
        ).read_text()

        # vault-commit post-hook ran, producing a third commit.
        log = _git(vault, ["log", "--oneline"]).stdout.strip().splitlines()
        assert len(log) == 3
        assert "awaiting-plan-review: 20260101-my-feature" in log[0]

        # Status stayed at the target (no spurious second frontmatter mutation).
        from booping.context._yaml import parse_frontmatter_only

        assert parse_frontmatter_only(plan)["status"] == "awaiting-plan-review"


