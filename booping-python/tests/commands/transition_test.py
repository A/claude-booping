# ---------------------------------------------------------------------------
# In-process fixtures for hook-injection scenarios.
#
# The dispatcher loads config via config_mod.load(plugin_root, []) and does NOT
# honour vault config overrides, so a synthetic config must be injected by
# monkeypatching the loader the dispatcher imports.
# ---------------------------------------------------------------------------

def _stub_project(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Make Project.load_cwd return a project whose vault is a writable tmp dir."""
    vault = tmp_path / "vault"
    (vault / "plans").mkdir(parents=True)

    def _fake_load_cwd(
        cls: type[Project], start: Path | None = None, home_dir: str = "~/Claude"
    ) -> Project:
        return Project(
            name="tproj",
            directory=vault,
            repo_directory=tmp_path,
            git_commit=None,
        )

    monkeypatch.setattr(Project, "load_cwd", classmethod(_fake_load_cwd))
    return vault


def _make_plan(vault: Path, status: str) -> Path:
    plan = vault / "plans" / "20260101-my-feature.md"
    plan.write_text(f"---\nstatus: {status}\ntitle: My feature\n---\n\n# Body\n")
    return plan


def _inject_config(
    monkeypatch: pytest.MonkeyPatch, hooks_for_edge: list[str]
) -> None:
    """Patch the config loader the dispatcher uses to return a one-edge config
    whose in-spec → awaiting-plan-review transition carries hooks_for_edge."""
    from booping.context import config as config_mod

    cfg: dict[str, Any] = {
        "plan": {
            "superstates": {
                "planning": {
                    "substates": ["in-spec", "awaiting-plan-review"],
                    "on_entry": [],
                }
            },
            "statuses": {
                "in-spec": {
                    "transitions": [
                        {
                            "to": "awaiting-plan-review",
                            "skill": "groom",
                            "hooks": hooks_for_edge,
                        }
                    ]
                },
                "awaiting-plan-review": {"transitions": []},
            },
            "hooks": {"post": []},
        }
    }

    def _fake_load(root: Path, overrides: list[Path]) -> dict[str, Any]:
        return cfg

    monkeypatch.setattr(config_mod, "load", _fake_load)


