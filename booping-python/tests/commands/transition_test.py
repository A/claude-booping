PLUGIN_ROOT = Path(__file__).resolve().parents[3]
BOOPING_BIN = PLUGIN_ROOT / "bin" / "booping"


# ---------------------------------------------------------------------------
# Subprocess fixture: a real git vault + a real git repo dir.
#
# Project.directory resolves to HOME/Claude/<name>, and vault-commit needs that
# directory to be a git repo; @head interpolation needs the repo dir (the one
# carrying .booping) to be a git repo too.
# ---------------------------------------------------------------------------

def _git(cwd: Path, args: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", *args],
        cwd=str(cwd),
        capture_output=True,
        text=True,
        check=True,
    )


def _init_git(directory: Path) -> None:
    _git(directory, ["init"])
    _git(directory, ["config", "user.email", "test@example.com"])
    _git(directory, ["config", "user.name", "Test"])


def _setup(tmp_path: Path) -> tuple[Path, Path, Path, dict[str, str]]:
    """Build a fake home + vault git repo + project repo dir.

    Returns (repo_dir, vault_dir, plan_path, env).
    - repo_dir carries .booping (project_name: tproj) and is a git repo (for @head).
    - vault_dir is fake_home/Claude/tproj, a git repo (for vault-commit), with an
      in-spec plan + sprints.md committed.
    - env has HOME pointing at the fake home.
    """
    fake_home = tmp_path / "home"
    vault = fake_home / "Claude" / "tproj"
    (vault / "plans").mkdir(parents=True)

    _init_git(vault)
    plan = vault / "plans" / "20260101-my-feature.md"
    plan.write_text(
        "---\nstatus: in-spec\ntitle: My feature\ntype: feature\nsp: 3\n"
        "planned: null\ncommit: null\n---\n\n# Plan body\n"
    )
    (vault / "sprints.md").write_text(
        "# Sprints\n\n| status | sp | title |\n| --- | --- | --- |\n"
    )
    _git(vault, ["add", "plans/20260101-my-feature.md", "sprints.md"])
    _git(vault, ["commit", "-m", "initial"])

    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / ".booping").write_text("project_name: tproj\n")
    _init_git(repo)
    (repo / "README.md").write_text("# repo\n")
    _git(repo, ["add", "README.md", ".booping"])
    _git(repo, ["commit", "-m", "repo initial"])

    env = dict(os.environ)
    env["HOME"] = str(fake_home)

    return repo, vault, plan, env


def _run_transition(
    repo: Path, env: dict[str, str], *cli_args: str
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [str(BOOPING_BIN), "transition", *cli_args],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )


