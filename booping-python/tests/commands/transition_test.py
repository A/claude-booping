# 1a. Transition report on stdout
# ---------------------------------------------------------------------------

class TestReport:
    def test_report_lines_match_contract(self, tmp_path: Path) -> None:
        repo, vault, plan, env = _setup(tmp_path)

        result = _run_transition(repo, env, "awaiting-plan-review", str(plan))
        assert result.returncode == 0, result.stderr

        lines = result.stdout.strip().splitlines()
        assert lines[0] == "in-spec → awaiting-plan-review"

        # status set, then the edge's planned/commit stamps.
        assert lines[1] == "frontmatter: status=awaiting-plan-review"
        # `planned=@now` resolves to "YYYYmmdd HH:MM" — quoted because it has a space.
        assert lines[2].startswith('frontmatter: planned="')
        assert lines[2].endswith('"')
        head = _git(repo, ["rev-parse", "HEAD"]).stdout.strip()
        assert lines[3] == f"frontmatter: commit={head}"

        assert lines[4] == f"render-sprints: 1 plans → {vault / 'sprints.md'}"

        short = _git(vault, ["rev-parse", "--short", "HEAD"]).stdout.strip()
        assert lines[5] == f"vault-commit: {short}"
        assert len(lines) == 6

    def test_stdout_carries_only_the_report(self, tmp_path: Path) -> None:
        repo, _vault, plan, env = _setup(tmp_path)

        result = _run_transition(repo, env, "awaiting-plan-review", str(plan))
        assert result.returncode == 0, result.stderr

        for line in result.stdout.strip().splitlines()[1:]:
            assert line.split(":")[0] in (
                "frontmatter",
                "render-sprints",
                "vault-commit",
            )

    def test_report_with_also(self, tmp_path: Path) -> None:
        repo, vault, plan, env = _setup(tmp_path)
        artifact = vault / "retro" / "20260101-my-feature.md"
        artifact.parent.mkdir(parents=True)
        artifact.write_text("# Retrospective\n")

        result = _run_transition(
            repo, env, "awaiting-plan-review", str(plan), "--also", str(artifact)
        )
        assert result.returncode == 0, result.stderr

        short = _git(vault, ["rev-parse", "--short", "HEAD"]).stdout.strip()
        lines = result.stdout.strip().splitlines()
        assert lines[0] == "in-spec → awaiting-plan-review"
        assert lines[-1] == f"vault-commit: {short}"

    def test_nothing_to_commit_reported(self, tmp_path: Path) -> None:
        repo, _vault, plan, env = _setup(tmp_path)

        first = _run_transition(repo, env, "awaiting-plan-review", str(plan))
        assert first.returncode == 0, first.stderr

        # Nothing changed since the first move: the vault-commit hook has no
        # diff to record.
        second = _run_transition(repo, env, "awaiting-plan-review", str(plan))
        assert second.returncode == 0, second.stderr

        lines = second.stdout.strip().splitlines()
        assert lines[0] == "awaiting-plan-review → awaiting-plan-review (idempotent)"
        assert lines[-1] == "vault-commit: nothing to commit"


